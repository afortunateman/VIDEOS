#!/usr/bin/env node
// Builds the browser data files used by the animation:
//   data/geo.js       simplified Natural Earth land polygons (lon/lat) + an Africa outline
//   data/glyphs.js    flattened glyph outlines for the title (Titan One) and subtitle (Pacifico)
//   data/timeline.js  the shared cue sheet (timeline.json) for the browser
// Everything is written as plain `window.X = ...` scripts so index.html also works from file://.

const fs = require('fs');
const path = require('path');
const opentype = require('opentype.js');

const ROOT = path.resolve(__dirname, '..');
const out = (name, varName, obj) => {
  const file = path.join(ROOT, 'data', name);
  fs.writeFileSync(file, `// generated by tools/build_data.js — do not edit\nwindow.${varName} = ${JSON.stringify(obj)};\n`);
  console.log('wrote', path.relative(ROOT, file), (fs.statSync(file).size / 1024).toFixed(1) + ' KB');
};

// ---------------------------------------------------------------- geography
function perpDist(p, a, b) {
  const dx = b[0] - a[0], dy = b[1] - a[1];
  const l2 = dx * dx + dy * dy;
  if (l2 === 0) return Math.hypot(p[0] - a[0], p[1] - a[1]);
  const t = Math.max(0, Math.min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / l2));
  return Math.hypot(p[0] - a[0] - t * dx, p[1] - a[1] - t * dy);
}
function simplify(pts, tol) {
  if (pts.length < 4) return pts.slice();
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [s, e] = stack.pop();
    let best = -1, bi = -1;
    for (let i = s + 1; i < e; i++) {
      const d = perpDist(pts[i], pts[s], pts[e]);
      if (d > best) { best = d; bi = i; }
    }
    if (best > tol) { keep[bi] = 1; stack.push([s, bi], [bi, e]); }
  }
  return pts.filter((_, i) => keep[i]);
}
function area(ring) {
  let a = 0;
  for (let i = 0, n = ring.length; i < n; i++) {
    const p = ring[i], q = ring[(i + 1) % n];
    a += p[0] * q[1] - q[0] * p[1];
  }
  return a / 2;
}
// split long edges so the rings bend smoothly when projected onto the globe
function densify(ring, maxSeg) {
  const res = [];
  for (let i = 0; i < ring.length; i++) {
    const p = ring[i], q = ring[(i + 1) % ring.length];
    res.push(p);
    const d = Math.hypot(q[0] - p[0], q[1] - p[1]);
    const k = Math.ceil(d / maxSeg);
    for (let j = 1; j < k; j++) res.push([p[0] + (q[0] - p[0]) * j / k, p[1] + (q[1] - p[1]) * j / k]);
  }
  return res;
}
const r1 = (v) => Math.round(v * 10) / 10;

const geo = JSON.parse(fs.readFileSync(path.join(ROOT, 'assets', 'ne_110m_land.geojson'), 'utf8'));
let rings = [];
for (const f of geo.features) {
  const g = f.geometry;
  const polys = g.type === 'MultiPolygon' ? g.coordinates : [g.coordinates];
  for (const p of polys) rings.push(p[0].slice(0, -1)); // outer ring, drop duplicate closing point
}
rings = rings
  .map((r) => ({ raw: r, simp: simplify(r.concat([r[0]]), 0.45).slice(0, -1) }))
  .filter((r) => r.simp.length >= 4 && Math.abs(area(r.simp)) > 1.6)
  .sort((a, b) => Math.abs(area(b.simp)) - Math.abs(area(a.simp)));

// Africa: cut the merged Afro-Eurasian ring at the Suez isthmus
const afroEurasia = rings[0].simp;
const nearest = (ring, lon, lat) => {
  let bi = 0, bd = 1e9;
  ring.forEach((p, i) => { const d = Math.hypot(p[0] - lon, p[1] - lat); if (d < bd) { bd = d; bi = i; } });
  return bi;
};
const iSuez = nearest(afroEurasia, 32.6, 29.9);   // Gulf of Suez head
const iSaid = nearest(afroEurasia, 32.3, 31.3);   // Port Said, Mediterranean side
const n = afroEurasia.length;
const walk = (a, b) => { const r = []; for (let i = a; ; i = (i + 1) % n) { r.push(afroEurasia[i]); if (i === b) break; } return r; };
let africa = walk(iSuez, iSaid);
let eurasia = walk(iSaid, iSuez);
if (!africa.some((p) => p[1] < -30)) { const tmp = africa; africa = eurasia; eurasia = tmp; }
// make the ring start on the East African coast (Tanzania) — where the journey's coastline lives
const iTz = nearest(africa, 39.4, -6.8);
africa = africa.slice(iTz).concat(africa.slice(0, iTz));

const ANTI = (p) => Math.abs(Math.abs(p[0]) - 180) < 0.01 || p[1] < -89.9;
const land = rings.map((r) => {
  const d = densify(r.simp, 2.5);
  return {
    pts: d.map((p) => [r1(p[0]), r1(p[1])]),
    // edges that are only artefacts of the dateline/pole cuts are not inked
    noInk: d.map((p, i) => (ANTI(p) && ANTI(d[(i + 1) % d.length]) ? 1 : 0)),
    area: Math.round(Math.abs(area(r.simp))),
  };
});
out('geo.js', 'WX_GEO', {
  land,
  africa: densify(africa.concat([africa[0]]), 1.6).map((p) => [r1(p[0]), r1(p[1])]),
  eurasia: densify(eurasia, 2.5).map((p) => [r1(p[0]), r1(p[1])]),
});

// ---------------------------------------------------------------- glyphs
function flattenGlyphPath(p, scale, step) {
  // returns contours as arrays of [x,y] in em units (y down)
  const contours = [];
  let cur = null, x = 0, y = 0;
  const push = (px, py) => cur.push([+(px * scale).toFixed(4), +(py * scale).toFixed(4)]);
  for (const c of p.commands) {
    if (c.type === 'M') { cur = []; contours.push(cur); x = c.x; y = c.y; push(x, y); }
    else if (c.type === 'L') { x = c.x; y = c.y; push(x, y); }
    else if (c.type === 'Q' || c.type === 'C') {
      const len = Math.hypot(c.x - x, c.y - y) + (c.type === 'Q' ? Math.hypot(c.x1 - x, c.y1 - y) : Math.hypot(c.x2 - c.x1, c.y2 - c.y1));
      const k = Math.max(2, Math.ceil(len / step));
      for (let i = 1; i <= k; i++) {
        const t = i / k, u = 1 - t;
        let px, py;
        if (c.type === 'Q') { px = u * u * x + 2 * u * t * c.x1 + t * t * c.x; py = u * u * y + 2 * u * t * c.y1 + t * t * c.y; }
        else {
          px = u * u * u * x + 3 * u * u * t * c.x1 + 3 * u * t * t * c.x2 + t * t * t * c.x;
          py = u * u * u * y + 3 * u * u * t * c.y1 + 3 * u * t * t * c.y2 + t * t * t * c.y;
        }
        push(px, py);
      }
      x = c.x; y = c.y;
    } else if (c.type === 'Z') {
      if (cur && cur.length > 1) {
        const a = cur[0], b = cur[cur.length - 1];
        if (Math.abs(a[0] - b[0]) < 1e-4 && Math.abs(a[1] - b[1]) < 1e-4) cur.pop();
      }
    }
  }
  return contours.filter((c) => c.length > 2);
}

function layoutText(fontFile, text, opts = {}) {
  const font = opentype.loadSync(path.join(ROOT, 'fonts', fontFile));
  const upm = font.unitsPerEm;
  const glyphs = font.stringToGlyphs(text);
  let pen = 0;
  const res = [];
  glyphs.forEach((g, i) => {
    const chr = text[i];
    const gp = g.getPath(0, 0, upm); // 1 unit = 1 font unit, y down
    const contours = flattenGlyphPath(gp, 1 / upm, opts.step || 14);
    const bb = gp.getBoundingBox();
    res.push({
      ch: chr,
      x: +(pen / upm).toFixed(4),
      adv: +(g.advanceWidth / upm).toFixed(4),
      bbox: [bb.x1 / upm, bb.y1 / upm, bb.x2 / upm, bb.y2 / upm].map((v) => +v.toFixed(4)),
      contours,
    });
    pen += g.advanceWidth + (opts.tracking || 0) * upm;
    if (i < glyphs.length - 1) pen += font.getKerningValue(g, glyphs[i + 1]);
  });
  return {
    text,
    width: +(pen / upm).toFixed(4),
    ascender: font.ascender / upm,
    descender: font.descender / upm,
    capHeight: (font.tables.os2 && font.tables.os2.sCapHeight ? font.tables.os2.sCapHeight : font.ascender * 0.7) / upm,
    glyphs: res,
  };
}

out('glyphs.js', 'WX_GLYPHS', {
  title: layoutText('TitanOne-Regular.ttf', 'WORLD.EXE', { tracking: 0.02, step: 12 }),
  subtitle: layoutText('Pacifico-Regular.ttf', 'by Legally Varun', { step: 12 }),
});

// ---------------------------------------------------------------- timeline
out('timeline.js', 'WX_TIMELINE', JSON.parse(fs.readFileSync(path.join(ROOT, 'timeline.json'), 'utf8')));
